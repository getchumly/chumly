//! UI strings. Every string is defined in both languages at once,
//! so a missing translation is a compile error.
//! Placeholders are written as {name} and filled in by `fill`.

use crate::config::Language;

macro_rules! strings {
    ($($key:ident => $ru:expr, $en:expr;)*) => {
        pub struct Tr { $(pub $key: &'static str,)* }
        pub const RU: Tr = Tr { $($key: $ru,)* };
        pub const EN: Tr = Tr { $($key: $en,)* };
        #[cfg(test)]
        impl Tr {
            /// Every string, for checks over all of them.
            pub fn all(&self) -> Vec<&'static str> {
                vec![$(self.$key,)*]
            }
        }
    };
}

